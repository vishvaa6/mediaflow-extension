import {readFileSync,writeFileSync,readdirSync} from 'node:fs';
const root=new URL('../assets/icons/',import.meta.url),icons={};
for(const name of readdirSync(root).filter(name=>name.endsWith('.svg'))){
  icons[name.slice(0,-4)]=readFileSync(new URL(name,root),'utf8').replace(/<!--[\s\S]*?-->/g,'').trim().replace(/class="[^"]*"/,'class="mf-icon" aria-hidden="true" focusable="false"').replace(/\s+/g,' ');
}
writeFileSync(new URL('../assets/js/icons.js',import.meta.url),`// Lucide SVGs. See assets/icons/LICENSE. Generated by scripts/build-icons.mjs.\nconst icons=${JSON.stringify(icons)};\nexport const icon=name=>icons[name] || icons.video;\n`);
